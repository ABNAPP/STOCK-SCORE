/** Values referenced by `eodhdExchangeSlugAliases.ts` — always merged into output. */
const ALIAS_TARGET_CODES = ['LSE', 'PA', 'AS', 'XETRA', 'MI', 'MC', 'CO', 'HE', 'TO', 'SW', 'AU', 'VI'];

function emitGeneratedTs(codes) {
  const unique = [...new Set(codes.filter(Boolean))].sort((a, b) => a.localeCompare(b));
  const recordPairs = unique.map((c) => `  ${JSON.stringify(c.toUpperCase())}: ${JSON.stringify(c)},`);
  return `/* eslint-disable -- generated by scripts/sync-eodhd-exchanges.mjs */
/* Do not edit by hand. Regenerate: npm run eodhd:sync-exchanges */
/** Uppercase lookup → canonical \`Code\` string from EODHD exchanges-list */
export const EODHD_EXCHANGE_CODE_CANONICAL: Readonly<Record<string, string>> = {
${recordPairs.join('\n')}
};

export function canonicalEodhdExchangeCode(upper: string): string | null {
  const k = upper.trim().toUpperCase();
  return EODHD_EXCHANGE_CODE_CANONICAL[k] ?? null;
}
`;
}

async function main() {
  const token = (process.env.EODHD_API_KEY || process.env.VITE_EODHD_API_KEY || '').trim();
  let codes = [];

  if (token) {
    const url = `https://eodhd.com/api/exchanges-list/?api_token=${encodeURIComponent(token)}&fmt=json`;
    const res = await fetch(url);
    if (!res.ok) {
      console.warn('sync-eodhd-exchanges: HTTP', res.status, '— using fallback codes');
    } else {
      const data = await res.json();
      if (Array.isArray(data)) {
        codes = data.map((row) => row?.Code).filter(Boolean);
        console.log('sync-eodhd-exchanges: fetched', codes.length, 'exchange codes from EODHD');
      } else {
        console.warn('sync-eodhd-exchanges: unexpected JSON shape — using fallback codes');
      }
    }
  } else {
    console.warn('sync-eodhd-exchanges: no EODHD_API_KEY / VITE_EODHD_API_KEY — using fallback codes');
  }

  if (codes.length === 0) {
    codes = [...FALLBACK_CODES];
  }

  codes = [...new Set([...codes, ...ALIAS_TARGET_CODES])];

  const ts = emitGeneratedTs(codes);
  const outApp = path.join(repoRoot, 'src/services/ism/marketData/eodhdExchangeGenerated.ts');
  const outFn = path.join(repoRoot, 'functions/src/eodhdExchangeGenerated.ts');
  fs.writeFileSync(outApp, ts, 'utf8');
  fs.writeFileSync(outFn, ts, 'utf8');
  console.log('Wrote', path.relative(repoRoot, outApp));
  console.log('Wrote', path.relative(repoRoot, outFn));

  const aliasesSrc = path.join(repoRoot, 'src/services/ism/marketData/eodhdExchangeSlugAliases.ts');
  const aliasesFn = path.join(repoRoot, 'functions/src/eodhdExchangeSlugAliases.ts');
  if (fs.existsSync(aliasesSrc)) {
    fs.copyFileSync(aliasesSrc, aliasesFn);
    console.log('Copied eodhdExchangeSlugAliases.ts → functions/src/');
  }

  const resolveSrc = path.join(repoRoot, 'src/services/ism/marketData/eodhdExchangeResolve.ts');
  const resolveFn = path.join(repoRoot, 'functions/src/eodhdExchangeResolve.ts');
  if (fs.existsSync(resolveSrc)) {
    fs.copyFileSync(resolveSrc, resolveFn);
    console.log('Copied eodhdExchangeResolve.ts → functions/src/');
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
