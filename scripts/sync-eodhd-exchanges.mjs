/**
 * Fetches https://eodhd.com/api/exchanges-list/ and writes canonical EODHD exchange codes
 * into TypeScript modules used by `eodhdExchangeResolve.ts` (app + Cloud Functions).
 *
 * Env: `EODHD_API_KEY` or `VITE_EODHD_API_KEY` (optional — falls back to bundled minimal list).
 *
 * Usage: node scripts/sync-eodhd-exchanges.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');

function loadDotEnvLocal() {
  const p = path.join(repoRoot, '.env.local');
  if (!fs.existsSync(p)) return;
  const raw = fs.readFileSync(p, 'utf8');
  for (const line of raw.split('\n')) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!m) continue;
    const k = m[1];
    let v = m[2].trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1);
    }
    if (process.env[k] === undefined) process.env[k] = v;
  }
}

loadDotEnvLocal();

/** Minimal subset when the API is unavailable (live sync replaces with full exchanges-list). */
